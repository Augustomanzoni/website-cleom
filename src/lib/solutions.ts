export const findSolution = (slug: string) => solutions.find((s) => s.slug === slug);
export const findProduct = (categoria: string, produtoSlug: string) => {
  const sol = findSolution(categoria);
  if (!sol) return null;
  const product = sol.products.find((p) => p.slug === produtoSlug);
  return product ? { solution: sol, product } : null;
};
